// glyphBits 是 glyphShapes 的位图编译结果,每字节低 5 位对应一行的 5 个像素(高位在左)。
var glyphBits = buildGlyphs()

func buildGlyphs() map[rune][7]byte {
	m := make(map[rune][7]byte, len(glyphShapes))
	for r, rows := range glyphShapes {
		var b [7]byte
		for i, row := range rows {
			for col := 0; col < 5; col++ {
				if row[col] == '#' {
					b[i] |= 1 << (4 - col)
				}
			}
		}
		m[r] = b
	}
	return m
}
