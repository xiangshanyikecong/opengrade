package omr

import (
	"math"
	"testing"
)

func TestRowThreshold(t *testing.T) {
	cases := []struct {
		name   string
		ratios []float64
		global float64
		want   float64
	}{
		{"单元素行回退全局", []float64{0.5}, 0.42, 0.42},
		{"清晰双组行取台阶中点", []float64{0.02, 0.03, 0.55, 0.02}, 0.42, 0.29},
		{"轻涂单标下探到夹持下限", []float64{0.35, 0.02, 0.03, 0.02}, 0.42, 0.27},
		{"多选双涂", []float64{0.02, 0.5, 0.48, 0.03}, 0.42, 0.27},
		{"空白行回退全局", []float64{0.02, 0.03, 0.01, 0.02}, 0.42, 0.42},
		{"整行饱满无台阶回退全局(全局本就全判已涂)", []float64{0.5, 0.45, 0.55, 0.48}, 0.42, 0.42},
		{"整行轻涂无台阶回退全局", []float64{0.3, 0.31, 0.3, 0.32}, 0.42, 0.42},
		{"Bradley噪声地板上的空白行回退全局", []float64{0.28, 0.26, 0.27, 0.25}, 0.42, 0.42},
		{"Bradley空白地板+实心涂点取台阶中点", []float64{0.27, 0.82, 0.28, 0.27, 0.28}, 0.42, 0.42},
		{"跳变不足回退全局", []float64{0.2, 0.25, 0.3, 0.25}, 0.42, 0.42},
		{"候选不向上收紧", []float64{0.02, 0.9, 0.02, 0.02}, 0.42, 0.42},
		{"低全局下高侧夹持", []float64{0.02, 0.9}, 0.7, 0.55},
	}
	for _, c := range cases {
		if got := rowThreshold(c.ratios, c.global); math.Abs(got-c.want) > 1e-9 {
			t.Errorf("%s: rowThreshold = %v, 期望 %v", c.name, got, c.want)
		}
	}
}
